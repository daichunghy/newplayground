const test = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const { harness, read } = require('./support/browser-harness.cjs');

function setup() {
  const h = harness({ loadEngines: false, loadApp: false });
  vm.runInContext(read('scripts/games/day-thung-sokoban-model.js'), h.context, { filename: 'day-thung-sokoban-model.js' });
  vm.runInContext(read('scripts/games/day-thung-sokoban.js'), h.context, { filename: 'day-thung-sokoban.js' });
  const ui = h.context.NP_DayThungSokoban.mount(h.container);
  return { h, ui };
}

const element = (h, selector) => h.container.querySelector(selector);
const cell = (h, x, y) => h.container.querySelectorAll('.np-soko-cell').find(item => Number(item.dataset.x) === x && Number(item.dataset.y) === y);
const key = (target, value) => target.dispatch('keydown', { key: value, preventDefault() { this.prevented = true; } });

function close(h, ui) {
  ui.destroy();
  h.context.NP_GameSession.stop();
  assert.equal(h.container.children.length, 0);
  assert.equal(h.window.listenerCount(), 0);
  assert.deepEqual(h.errors, []);
}

test('mounts instantly with an accessible board, live status, and compact controls', () => {
  const { h, ui } = setup();
  assert.match(h.container.innerHTML, /Đẩy Thùng/);
  assert.equal(element(h, '.np-soko-board').getAttribute('role'), 'grid');
  assert.equal(element(h, '.np-soko-board').getAttribute('tabindex'), '0');
  assert.equal(element(h, '.np-soko-status').getAttribute('aria-live'), 'polite');
  assert.equal(h.container.querySelectorAll('.np-soko-cell').length, 40);
  assert.match(element(h, '.np-soko-status').textContent, /Đẩy từng thùng/);
  assert.equal(element(h, '.np-soko-next').hidden, true);
  close(h, ui);
});

test('arrow keys and WASD move exactly one tile; Z undoes and R restarts', () => {
  const { h, ui } = setup();
  const board = element(h, '.np-soko-board');
  key(board, 'ArrowRight');
  key(board, 'w');
  assert.deepEqual(JSON.parse(JSON.stringify(ui.model.view().player)), { x: 5, y: 2 });
  assert.equal(ui.model.view().moves, 2);
  key(board, 'z');
  assert.equal(ui.model.view().moves, 1);
  key(board, 'R');
  assert.equal(ui.model.view().moves, 0);
  assert.deepEqual(JSON.parse(JSON.stringify(ui.model.view().player)), { x: 4, y: 3 });
  close(h, ui);
});

test('direction buttons move the player and report a blocked step', () => {
  const { h, ui } = setup();
  element(h, '.np-soko-arrow.is-right').click();
  assert.equal(ui.model.view().player.x, 5);
  element(h, '.np-soko-arrow.is-down').click();
  assert.match(element(h, '.np-soko-status').textContent, /Đường bị chặn/);
  close(h, ui);
});

test('tapping a board cell chooses a step toward it', () => {
  const { h, ui } = setup();
  element(h, '.np-soko-board').dispatch('click', { target: cell(h, 5, 3) });
  assert.deepEqual(JSON.parse(JSON.stringify(ui.model.view().player)), { x: 5, y: 3 });
  assert.equal(ui.model.view().moves, 1);
  close(h, ui);
});

test('swipe input uses the dominant direction and ignores short pointer motion', () => {
  const { h, ui } = setup();
  const board = element(h, '.np-soko-board');
  board.dispatch('pointerdown', { pointerId: 7, isPrimary: true, button: 0, clientX: 40, clientY: 50 });
  h.window.dispatch('pointerup', { pointerId: 7, clientX: 44, clientY: 52 });
  assert.equal(ui.model.view().moves, 0);
  board.dispatch('pointerdown', { pointerId: 8, isPrimary: true, button: 0, clientX: 40, clientY: 50 });
  h.window.dispatch('pointerup', { pointerId: 8, clientX: 12, clientY: 50 });
  assert.equal(ui.model.view().player.x, 3);
  assert.equal(ui.model.view().moves, 1);
  board.dispatch('click', { target: cell(h, 2, 3) });
  assert.equal(ui.model.view().player.x, 3, 'the click generated by a swipe must not make a second move');
  close(h, ui);
});

test('undo, restart, and level progression update visible state and win announcement', () => {
  const { h, ui } = setup();
  for (const direction of ['right', 'right', 'up', 'left', 'left', 'left']) element(h, `.np-soko-arrow.is-${direction}`).click();
  assert.equal(ui.model.view().status, 'won');
  assert.equal(element(h, '.np-soko-next').hidden, false);
  assert.match(element(h, '.np-soko-status').textContent, /Màn 1 hoàn thành/);
  element(h, '.np-soko-next').click();
  assert.equal(ui.model.view().levelIndex, 1);
  assert.equal(ui.model.view().moves, 0);
  element(h, '.np-soko-reset').click();
  assert.equal(ui.model.view().levelIndex, 1);
  assert.equal(ui.model.view().moves, 0);
  element(h, '.np-soko-undo').click();
  assert.equal(ui.model.view().moves, 0);
  close(h, ui);
});

test('session cleanup is idempotent and removes keyboard and pointer listeners', () => {
  const { h, ui } = setup();
  assert.equal(h.window.listenerCount(), 2);
  ui.destroy();
  h.context.NP_GameSession.stop();
  ui.destroy();
  assert.equal(h.window.listenerCount(), 0);
  assert.equal(h.container.children.length, 0);
});

test('repeated mounts do not accumulate window listeners', () => {
  for (let i = 0; i < 8; i += 1) {
    const { h, ui } = setup();
    assert.equal(h.window.listenerCount(), 2);
    close(h, ui);
  }
});

