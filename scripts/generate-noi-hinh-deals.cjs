#!/usr/bin/env node
/* Offline pool builder. Runtime stage starts use these certified entries. */
const fs = require('node:fs');
const path = require('node:path');
const M = require('./games/noi-hinh-model.js');

const requestedCount = process.argv.slice(2).find(value => value.startsWith('--per-stage='))?.slice('--per-stage='.length);
const PER_STAGE = requestedCount === undefined ? 64 : Number(requestedCount);
if (!Number.isSafeInteger(PER_STAGE) || PER_STAGE < 1 || PER_STAGE > 1024) {
  throw new Error('--per-stage must be an integer from 1 through 1024');
}
const OUTPUT = path.join(__dirname, 'games', 'noi-hinh-certified-deals.js');
const pools = [];
let maxWork = 0;
let fallbackCount = 0;

for (const stage of M.CAMPAIGN) {
  const pool = [];
  const seen = new Set();
  for (let index = 0; index < PER_STAGE; index++) {
    let seed = (0x4e6f6948 ^ Math.imul(stage.stage, 0x9e3779b9) ^ Math.imul(index + 1, 0x85ebca6b)) >>> 0;
    if (!seed) seed = 1;
    const deal = M.makeSolverDeal(stage.stage, seed);
    if (!M.verifyWitness(deal.board, deal.witness, stage.stage)) {
      throw new Error(`Witness check failed for stage ${stage.stage}, template ${index}`);
    }
    const boardKey = deal.board.join(',');
    if (seen.has(boardKey)) throw new Error(`Duplicate board at stage ${stage.stage}, template ${index}`);
    seen.add(boardKey);
    maxWork = Math.max(maxWork, deal.work);
    if (deal.stats.fallback) fallbackCount++;
    pool.push([seed, deal.board, deal.witness.map(pair => [pair.a, pair.b])]);
  }
  pools.push(pool);
}

const data = JSON.stringify(pools);
const source = `/* Generated by scripts/generate-noi-hinh-deals.cjs; witnesses are checked by the model suite. */\n` +
  `(function(root, data) {\n  if (typeof module === 'object' && module.exports) module.exports = data;\n` +
  `  if (root) root.NP_NoiHinhCertifiedDeals = data;\n})(typeof window === 'object' ? window : null, ${data});\n`;
fs.writeFileSync(OUTPUT, source, 'utf8');
process.stdout.write(`${JSON.stringify({ output: path.relative(process.cwd(), OUTPUT), pools: pools.length,
  dealsPerStage: PER_STAGE, verifiedWitnesses: pools.reduce((sum, pool) => sum + pool.length, 0),
  maxOfflineSolverWork: maxWork, offlineFallbacks: fallbackCount, bytes: Buffer.byteLength(source) }, null, 2)}\n`);
